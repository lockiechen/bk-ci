  FLOW_DETAIL_NOTIFICATION_CONFIG: 'notificationConfig',
  FLOW_DETAIL_BASIC_SETTINGS: 'basicSettings',
  FLOW_DETAIL_PERMISSION_SETTINGS: 'permissionSettings',
