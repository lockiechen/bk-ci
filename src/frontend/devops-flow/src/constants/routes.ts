  ROOT: 'root',
  FLOW_LIST: 'flowList',
  TEMPLATE: 'template',

  // Flow 详情相关路由
  FLOW_DETAIL: 'flowDetail',
  FLOW_DETAIL_EDIT: 'flowDetailEdit',

  // Flow Detail 子路由
